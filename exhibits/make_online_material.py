"""Write the online material of the IJTLD manuscript into docs/online_material/ from outputs/.

Run as: python -I exhibits/make_online_material.py

The IJTLD charges for journal supplements, so every table and figure that is not one of the
manuscript's three display items is published here, in the public repository, and cited in the
text as online material. Everything is an aggregate computed from the committed outputs/ (Table
S1: the committed extraction in data/extracted/dm_panel.csv) by the committed exhibit code;
nothing is typed in by hand, and no individual-level data exist in this study.

Writes docs/online_material/:
  README.md            the index, the notation and how the files were made
  tables.md            Tables S1-S15, numbered in the order of their first citation in the
                       manuscript (ORDER below): the supplementary tables of exhibits/make_tables.py
                       and the headline estimates H1, H2 and H3 with the national scenario
  tableS1.csv ...      one CSV per table, the same rows
  figureS1.pdf/.png    the 2023 screening, identification and linkage gaps by unit, with tiers
  figureS2.pdf/.png    the overdispersed funnel of identification (2023, 2021 and 2019)
  figureS1_data.csv, figureS2_data.csv   the values each figure plots

The wording is person-first ("people with TB", never "TB patients"), as in the manuscript.
verification/check_online_material.py regenerates every text file and requires it to be
identical, and checks the wording.
"""
