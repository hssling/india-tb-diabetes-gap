def readme(root: Path = ROOT) -> str:
    ts = tables(root)
    lines = [
        "# Online material",
        "",
        "Online material for the manuscript \"Beyond screening: the tuberculosis–diabetes care cascade across India's "
        "States, 2018–2023\". Every file here is generated by `exhibits/make_online_material.py` from the committed "
        "`outputs/` (Table S1 from the committed extraction in `data/extracted/`), and checked by "
        "`verification/check_online_material.py`. All values are aggregates of published State and Union Territory "
        "tables; the study holds no individual-level data.",
        "",
        "## Tables",
        "",
        "All tables are in [`tables.md`](tables.md); each is also a CSV file.",
        "",
        "| Table | Title | CSV |",
        "|---|---|---|",
    ]
    for t in ts:
        lines.append(f"| {t.label} | {t.title} | [`{csv_name(t)}`]({csv_name(t)}) |")
    lines += ["", "## Figures", ""]
    for k in FIGURES:
        lines += [f"- [`figure{k}.pdf`](figure{k}.pdf) ([PNG preview](figure{k}.png); data "
                  f"[`figure{k}_data.csv`](figure{k}_data.csv)). {CAPTIONS[k]}"]
    lines += ["", "## Notation", "", "The manuscript describes these quantities in words; the tables use the symbols.", "",
              "| Symbol | Meaning |", "|---|---|"]
    lines += [f"| {a} | {b} |" for a, b in NOTATION]
    lines += ["", "TB, tuberculosis; NFHS-5, National Family Health Survey 2019-21; NCD, non-communicable disease; "
              "UT, Union Territory.", "",
              f"Repository: {REPO}. The analysis plan ([`docs/analysis_plan.md`](../analysis_plan.md)) was "
              "time-stamped in this public repository before estimation.", ""]
    return "\n".join(lines)


def text_files(root: Path = ROOT) -> dict[str, bytes]:
    """Every generated text file of docs/online_material/ (name -> bytes)."""
    out = {"README.md": readme(root).encode("utf-8"), "tables.md": tables_md(root).encode("utf-8")}
    for t in tables(root):
        out[csv_name(t)] = make_tables.csv_bytes(t)
    for k, (data, _) in FIGURES.items():
        out[f"figure{k}_data.csv"] = make_figures.data_csv(data(root))
    return out


def write(root: Path = ROOT) -> list[str]:
    out_dir = root / OUT_REL
    out_dir.mkdir(parents=True, exist_ok=True)
    files = text_files(root)
    for name, data in files.items():
        (out_dir / name).write_bytes(data)
    plt = make_figures.setup()
    for k, (data, draw) in FIGURES.items():
        fig = draw(data(root), plt)
        relabel(fig)
        fig.savefig(out_dir / f"figure{k}.pdf", metadata={"CreationDate": None, "Creator": None, "Producer": None})
        fig.savefig(out_dir / f"figure{k}.png", dpi=200)
        plt.close(fig)
    return sorted(files) + [f"figure{k}.pdf" for k in FIGURES] + [f"figure{k}.png" for k in FIGURES]


def main() -> int:
    if len(sys.argv) > 1:
        print(f"unknown arguments {sys.argv[1:]}")
        return 2
    names = write(ROOT)
    print(f"wrote {len(names)} files into {OUT_REL}/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
