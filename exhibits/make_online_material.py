def relabel(fig) -> None:
    """Person-first figure text (axis labels and titles drawn by exhibits/make_figures.py)."""
    for ax in fig.axes:
        ax.set_xlabel(person_first(ax.get_xlabel()))
        ax.set_ylabel(person_first(ax.get_ylabel()))
        ax.set_title(person_first(ax.get_title(loc="left")), loc="left", fontweight="bold", fontsize=6.4)
        for t in ax.texts:
            t.set_text(person_first(t.get_text()))


