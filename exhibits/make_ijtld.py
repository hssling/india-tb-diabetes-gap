"""Write the display items of the IJTLD manuscript (manuscript/v2) from outputs/.

Run as: python -I exhibits/make_ijtld.py [--manuscript-dir DIR]   (default: manuscript/v2)

The IJTLD Original Article allows at most three display items within its six typeset pages,
so the manuscript has one table and two figures; everything else is online material
(exhibits/make_online_material.py, committed under docs/online_material/).

Writes into <DIR>/exhibits/:
  tables.md, table1.csv   Table 1: the 2023 State cascade (screening coverage, identification
                          relative to the benchmark, linkage, where the shortfall lies, the five
                          largest absolute gaps and the shortfall per 100 000 notified)
  figure1.pdf/.png        Figure 1: the national cascade by data year, one compact row
  figure2.pdf/.png        Figure 2: State screening coverage against identification relative
                          to the benchmark, marked by where the shortfall lies
  figure1_data.csv, figure2_data.csv   the values each figure plots (make_figures.fig1_data and
                          fig2_data, read from outputs/)

Every cell and label is computed from outputs/ with exhibits/formats.py and written in the IJTLD
style (no-break-space thousands, en-dash intervals). The figures are black and white with Arial
lettering, as the journal asks. The number check regenerates tables.md and the data CSVs and
requires them to be identical. The PDFs carry no creation date.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from exhibits.formats import (count, ijtld_style, num, one, pct, ratio, read_csv,  # noqa: E402
                              state_rows)
from exhibits.make_figures import CODE, CLASS_MARK, data_csv, fig1_data, fig2_data, place_labels  # noqa: E402
from exhibits.make_tables import Table, csv_bytes, render_md  # noqa: E402

DEFAULT_MS_DIR = "manuscript/v2"
HEADER = "# Tables (generated by exhibits/make_ijtld.py from outputs/; do not edit by hand)"
MAIN_YEAR = "2023"
WIDTH = 6.85  # inches (174 mm), the full text width
BLACK, GREY, LIGHT = "#000000", "#6e6e6e", "#bdbdbd"
DASH = "—"
GAP_LETTER = {"E1": "S", "E2": "I", "E3": "L"}
CLASS_WORD = {"identification-led": "Identification", "screening-led": "Screening", "mixed": "Mixed"}


# --------------------------------------------------------------------------------------
# Table 1
# --------------------------------------------------------------------------------------
def table1(root: Path = ROOT) -> Table:
    ca = sorted((r for r in state_rows(read_csv(root, "outputs/cascade.csv"))
                 if r["spec"] == "main" and r["year"] == MAIN_YEAR), key=lambda r: r["unit"])
    dc = {r["unit"]: r for r in read_csv(root, "outputs/decomposition.csv")
          if r["spec"] == "main" and r["year"] == MAIN_YEAR}
    pr = [r for r in read_csv(root, "outputs/priority.csv") if r["spec"] == "main" and r["year"] == MAIN_YEAR]
    big = {u: [GAP_LETTER[g] for g in ("E1", "E2", "E3")
               if one(pr, f"{u} {g}", unit=u, gap=g)["tier"] == "act now"] for u in (r["unit"] for r in ca)}
    rows = []
    for r in ca:
        u = r["unit"]
        tot = one(pr, f"{u} total", unit=u, gap="total")
        rows.append([u, num(100 * float(r["C1"]), 1), ijtld_style(f"{ratio(r['C2'])} ({ratio(r['C2_lo'])} to {ratio(r['C2_hi'])})"),
                     num(100 * float(r["C3"]), 1), CLASS_WORD[dc[u]["class"]], ", ".join(big[u]) or DASH,
                     ijtld_style(count(tot["per_100k_notified"]))])
    kb = one(read_csv(root, "outputs/benchmark.csv"), "main k_b", kind="k_b", is_main="True")["value"]
    n_scr = sum(dc[r["unit"]]["class"] == "screening-led" for r in ca)
    notes = [ijtld_style(
        f"Data year {MAIN_YEAR}; {count(len(ca))} States and Union Territories (small Union Territories merged with "
        f"neighbours). Screened: people notified with tuberculosis who had a known diabetes status. Identification "
        f"ratio: the share of those screened recorded with diabetes (known or newly found), divided by the benchmark "
        f"expectation, {ratio(kb, 3)} times the unit's National Family Health Survey 2019–21 prevalence of raised or "
        f"treated blood glucose; 1 means identification at the benchmark, the 75th percentile of units. CI = "
        f"confidence interval (Jeffreys, 10,000 posterior draws). Linked: started on anti-diabetic treatment among "
        f"those identified. Shortfall: where the unit's shortfall lies; screening-led or identification-led when the "
        f"screening gap's share of the screening and identification gaps is above or below one half with probability "
        f"at least 0.95, otherwise mixed. The {count(n_scr)} screening-led units are those at or above the "
        f"benchmark, where the identification gap is zero by definition. Largest gaps: among the five units with the "
        f"largest absolute screening (S), identification (I) or linkage (L) gap; the same five in every draw. Rate: "
        f"the screening and identification gaps together per 100,000 notified. A ratio below 1 may reflect a "
        f"truly lower prevalence, testing or recording, not only missed diabetes. TB = tuberculosis. Sources: India TB Report 2024; "
        f"National Family Health Survey 2019–21 State and Union Territory fact sheets.")]
    return Table("Table 1", "The tuberculosis–diabetes care cascade by State and Union Territory, 2023",
                 ["State or Union Territory", "Screened, %", "Identification ratio (95% CI)", "Linked, %",
                  "Shortfall", "Largest gaps", "Rate"], rows, notes)


def build(root: Path = ROOT) -> list[Table]:
    return [table1(root)]


def render(root: Path = ROOT) -> str:
    return render_md(build(root)).replace(
        "# Tables (generated by exhibits/make_tables.py from outputs/; do not edit by hand)", HEADER, 1)


# --------------------------------------------------------------------------------------
# Figures (black and white, Arial)
# --------------------------------------------------------------------------------------
FIGURES = {1: fig1_data, 2: fig2_data}


def setup():
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    plt.rcParams.update({
        "font.family": "Arial", "font.size": 7.5, "axes.titlesize": 7.5, "axes.labelsize": 7.5,
        "xtick.labelsize": 7, "ytick.labelsize": 7, "legend.fontsize": 7, "axes.linewidth": 0.6,
        "xtick.major.width": 0.5, "ytick.major.width": 0.5, "pdf.fonttype": 42, "svg.hashsalt": "dmgap",
        "axes.spines.top": False, "axes.spines.right": False, "hatch.linewidth": 0.6,
    })
    return plt


def draw1(rows: list[dict], plt):
    fig, axes = plt.subplots(1, 3, figsize=(WIDTH, 2.05))
    years = [int(r["year"]) for r in rows]
    panels = [("A  Screened", "C1"), ("B  Identified among screened", "y"), ("C  Started treatment", "C3")]
    for ax, (title, key) in zip(axes, panels):
        for r, yr in zip(rows, years):
            v = 100 * float(r[key])
            other = key == "C3" and r["C3_definition"] != "initiated on treatment"
            ax.bar(yr, v, width=0.7, color="white" if other else GREY, edgecolor=BLACK, lw=0.6,
                   hatch="////" if other else None)
            if key == "C1":
                ax.plot([yr, yr], [100 * float(r["C1_lo"]), 100 * float(r["C1_hi"])], color=BLACK, lw=0.8)
            ax.annotate(f"{num(v, 1)}", (yr, v), xytext=(0, 1.5), textcoords="offset points", ha="center",
                        va="bottom", fontsize=6.5)
        ax.set_xticks(years)
        ax.set_xticklabels([str(y) for y in years])
        ax.set_title(title, loc="left", fontweight="bold")
        top = 10 if key == "y" else 100
        ax.set_ylim(0, top * 1.12)
        ax.set_ylabel("%")
    fig.subplots_adjust(left=0.06, right=0.99, top=0.86, bottom=0.13, wspace=0.3)
    return fig


def draw2(rows: list[dict], plt):
    fig, ax = plt.subplots(figsize=(WIDTH, 4.0), dpi=100)
    cb = 100 * float(rows[0]["c_b"])
    ax.axhline(1.0, color=BLACK, ls="--", lw=0.8, zorder=1)
    ax.axvline(cb, color=GREY, ls=":", lw=0.9, zorder=1)
    pts = []
    for r in rows:
        x = 100 * float(r["C1"])
        y, lo, hi = float(r["C2"]), float(r["C2_lo"]), float(r["C2_hi"])
        m, filled = CLASS_MARK[r["class"]]
        ax.plot([x, x], [lo, hi], color=LIGHT, lw=0.8, zorder=2)
        ax.plot(x, y, marker=m, ms=4.5, mfc=BLACK if filled else "white", mec=BLACK, mew=0.8, ls="", zorder=3)
        pts.append((x, y, CODE[r["unit"]]))
    ax.set_yscale("log")
    ticks = [0.3, 0.5, 0.7, 1.0, 1.5, 2.0]
    ax.set_yticks(ticks)
    ax.set_yticklabels([num(t, 1) for t in ticks])
    ax.minorticks_off()
    xs = [100 * float(r["C1"]) for r in rows]
    ax.set_xlim(min(xs) - 3, 100.5)
    ax.set_ylim(0.22, 2.3)
    ax.set_xlabel("Screened for diabetes, % of people notified with tuberculosis (2023)")
    ax.set_ylabel("Identification relative to the benchmark (log scale)")
    ax.text(min(xs) - 2.6, 1.03, "identification at the benchmark", fontsize=6.5, va="bottom")
    ax.text(cb - 0.3, 0.23, f"benchmark coverage {num(cb, 1)}%", color=GREY, fontsize=6.5, ha="right", va="bottom")
    from matplotlib.lines import Line2D
    h = [Line2D([], [], marker=CLASS_MARK[c][0], ls="", mfc=BLACK if CLASS_MARK[c][1] else "white", mec=BLACK, ms=4.5)
         for c in ("identification-led", "screening-led", "mixed")]
    n = {c: sum(r["class"] == c for r in rows) for c in CLASS_MARK}
    ax.legend(h, [f"identification-led ({n['identification-led']})", f"screening-led ({n['screening-led']})",
                  f"mixed ({n['mixed']})"], loc="upper left", frameon=False, title="Where the shortfall lies",
              title_fontsize=7)
    fig.subplots_adjust(left=0.085, right=0.985, top=0.97, bottom=0.12)
    place_labels(ax, pts, fig)
    return fig


DRAW = {1: draw1, 2: draw2}


def write(ms_dir: Path, root: Path = ROOT, png: bool = True) -> list[str]:
    ex = ms_dir / "exhibits"
    ex.mkdir(parents=True, exist_ok=True)
    tables = build(root)
    (ex / "tables.md").write_text(render(root), encoding="utf-8", newline="\n")
    for t in tables:
        (ex / t.csv_name).write_bytes(csv_bytes(t))
    out = [f"{t.label}: {len(t.rows)} rows -> {t.csv_name}" for t in tables]
    plt = setup()
    for k, fn in FIGURES.items():
        rows = fn(root)
        (ex / f"figure{k}_data.csv").write_bytes(data_csv(rows))
        fig = DRAW[k](rows, plt)
        fig.savefig(ex / f"figure{k}.pdf", metadata={"CreationDate": None, "Creator": None, "Producer": None})
        if png:
            fig.savefig(ex / f"figure{k}.png", dpi=200)
        plt.close(fig)
        out.append(f"figure{k}.pdf: {len(rows)} data rows")
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0], allow_abbrev=False)
    ap.add_argument("--manuscript-dir", default=DEFAULT_MS_DIR)
    a = ap.parse_args(argv)
    d = Path(a.manuscript_dir)
    d = d if d.is_absolute() else ROOT / d
    for ln in write(d):
        print(ln)
    return 0


if __name__ == "__main__":
    sys.exit(main())
