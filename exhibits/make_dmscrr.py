"""Write the display items and the supplement of the Diabetes & Metabolic Syndrome: Clinical
Research & Reviews manuscript (manuscript/v3) from outputs/.

Run as: python -I exhibits/make_dmscrr.py [--manuscript-dir DIR]   (default: manuscript/v3)

The journal's Original research article allows five display items within its 5000 words; the
manuscript has one table and three figures, and a supplementary material file (free) carries the
other tables and one figure, numbered S1, S2, ... in the order of their first citation in the
manuscript (SUPPLEMENT_ORDER). Nothing is estimated here: every cell and label is read from
outputs/ with exhibits/formats.py, in the number style of the IJTLD set (no-break-space thousands,
en-dash intervals), which the number check of this profile also uses.

Writes into <DIR>/exhibits/:
  tables.md, table1.csv   Table 1: the 2023 State cascade, where the shortfall lies, the five
                          largest gaps, the shortfall per 100 000 notified and the step to
                          strengthen first (the fixed rule of exhibits/make_tables.guidance_step,
                          applied to existing outputs; formerly the online guidance table)
  supplement.md           Tables S1-S14 (the online tables of exhibits/make_online_material.py,
                          person-first, renumbered by first citation in this manuscript) and the
                          legend of Figure S1
  figure1.pdf/.png        Figure 1: the national cascade by data year (colour)
  figure2.pdf/.png        Figure 2: State screening coverage against identification relative to
                          the benchmark, marked by where the shortfall lies (colour and shape)
  figure3.pdf/.png        Figure 3: the 2023 screening, identification and linkage gaps by State
                          (formerly online Figure S1; colour)
  figureS1.pdf/.png       Figure S1: the overdispersed funnel (formerly online Figure S2)
  figure1_data.csv ... figure3_data.csv, figureS1_data.csv   the values each figure plots

Colours are from the Okabe-Ito palette (safe for colour-vision deficiency), and every class is
also told apart by marker shape. The PDFs carry no creation date; the PNGs are previews.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from exhibits import make_figures, make_online_material  # noqa: E402
from exhibits.formats import count, ijtld_style, num, one, ratio, read_csv, state_rows  # noqa: E402
from exhibits.make_figures import CODE, data_csv, fig1_data, fig2_data, fig3_data, fig4_data, place_labels  # noqa: E402
from exhibits.make_tables import Table, csv_bytes, render_md  # noqa: E402

DEFAULT_MS_DIR = "manuscript/v3"
HEADER = "# Tables (generated by exhibits/make_dmscrr.py from outputs/; do not edit by hand)"
SUPP_HEADER = "# Supplementary tables (generated by exhibits/make_dmscrr.py from outputs/; do not edit by hand)"
MAIN_YEAR = "2023"
WIDTH = 7.48  # inches: Elsevier full-page width (190 mm)
BLUE, ORANGE, GREEN, VERMILION, BLACK, GREY, LIGHT = ("#0072B2", "#E69F00", "#009E73", "#D55E00", "#000000",
                                                     "#7f7f7f", "#c8c8c8")
DASH = "—"
GAP_LETTER = {"E1": "S", "E2": "I", "E3": "L"}
CLASS_WORD = {"identification-led": "Identification", "screening-led": "Screening", "mixed": "Mixed"}
STEP_WORD = {"identification-led": "Identification", "screening-led": "Screening",
             "mixed": "Screening and identification"}
CLASS_STYLE = {"identification-led": ("o", BLUE, True), "screening-led": ("s", ORANGE, False),
               "mixed": ("^", GREEN, False)}

# The source tables of exhibits/make_tables.py in this manuscript's order of first citation
# (position n is Table Sn of the supplement). The guidance table is in Table 1 instead.
SUPPLEMENT_ORDER = ["Table S1",   # sources and definitions (Methods, data)
                    "Table S2",   # reference prevalence (Methods, data)
                    "Table S3",   # benchmarks (Methods, the benchmark)
                    "Table S4",   # national cascade by year and basis (Results)
                    "Table 1",    # headline estimates H1, H2, H3 and the scenario (Results)
                    "Table S5",   # the 2023 State cascade in full (Results)
                    "Table S10",  # H1 grid, Spearman, leave-one-out (Results)
                    "Table S6",   # linkage by year and the linkage gap (Results)
                    "Table S7",   # screening and identification gaps with tiers (Results)
                    "Table S8",   # where the shortfall lies (Results)
                    "Table S9",   # sensitivity analyses (Results)
                    "Table S13",  # perturbation (Results)
                    "Table S11",  # funnel (Results, with Figure S1)
                    "Table S12"]  # coverage trend (Discussion, limitations)
SUPPLEMENT_FIGURES = {"S1": "figureS1"}
FIGURE_S1_LEGEND = (
    "**Figure S1.** Overdispersed funnel of diabetes identified against the across-unit relationship with the "
    "reference prevalence, by the number screened: (A) 2023, expected values from the 2023 regression; (B) 2021 and "
    "(C) 2019, from the regression on 2019 and 2021. z is the standardised difference between identified and "
    "expected; limits are widened for overdispersion. Gujarat (triangle) lies below the 99.8% limit in each year; "
    "this may reflect testing, recording or the reference prevalence as much as missed diabetes.")


# --------------------------------------------------------------------------------------
# Table 1
# --------------------------------------------------------------------------------------
def first_step(cls: str, c3: float) -> str:
    """exhibits/make_tables.guidance_step in short words: linkage first where fewer than half of
    those identified started treatment, then the step named by where the shortfall lies."""
    return f"Linkage, then {STEP_WORD[cls].lower()}" if c3 < 0.5 else STEP_WORD[cls]


def table1(root: Path = ROOT) -> Table:
    ca = sorted((r for r in state_rows(read_csv(root, "outputs/cascade.csv"))
                 if r["spec"] == "main" and r["year"] == MAIN_YEAR), key=lambda r: r["unit"])
    dc = {r["unit"]: r for r in read_csv(root, "outputs/decomposition.csv")
          if r["spec"] == "main" and r["year"] == MAIN_YEAR}
    pr = [r for r in read_csv(root, "outputs/priority.csv") if r["spec"] == "main" and r["year"] == MAIN_YEAR]
    rows = []
    for r in ca:
        u = r["unit"]
        big = [GAP_LETTER[g] for g in ("E1", "E2", "E3") if one(pr, f"{u} {g}", unit=u, gap=g)["tier"] == "act now"]
        tot = one(pr, f"{u} total", unit=u, gap="total")
        rows.append([u, num(100 * float(r["C1"]), 1),
                     ijtld_style(f"{ratio(r['C2'])} ({ratio(r['C2_lo'])} to {ratio(r['C2_hi'])})"),
                     num(100 * float(r["C3"]), 1), CLASS_WORD[dc[u]["class"]], ", ".join(big) or DASH,
                     ijtld_style(count(tot["per_100k_notified"])), first_step(dc[u]["class"], float(r["C3"]))])
    kb = one(read_csv(root, "outputs/benchmark.csv"), "main k_b", kind="k_b", is_main="True")["value"]
    n_scr = sum(dc[r["unit"]]["class"] == "screening-led" for r in ca)
    notes = [ijtld_style(
        f"Data year {MAIN_YEAR}; {count(len(ca))} States and Union Territories (small Union Territories merged with "
        f"neighbours). Screened: people notified with tuberculosis who had a known diabetes status. Identification "
        f"ratio: the share of those screened recorded with diabetes (known or newly found), divided by the benchmark "
        f"expectation, {ratio(kb, 3)} times the unit's National Family Health Survey 2019–21 prevalence of raised or "
        f"treated blood glucose; 1 means identification at the benchmark, the 75th percentile of units. CI, "
        f"confidence interval (Jeffreys, 10,000 posterior draws). Linked: started on anti-diabetic treatment among "
        f"those identified. Shortfall: where the unit's shortfall lies; screening-led or identification-led when the "
        f"screening gap's share of the screening and identification gaps is above or below one half with probability "
        f"at least 0.95, otherwise mixed. The {count(n_scr)} screening-led units are those at or above the "
        f"benchmark, where the identification gap is zero by definition. Largest gaps: among the five units with the "
        f"largest absolute screening (S), identification (I) or linkage (L) gap; the same five in every draw. Rate: "
        f"the screening and identification gaps together per 100,000 notified. First step: linkage where fewer than "
        f"half of those identified started treatment, then the step where the shortfall lies; options for the "
        f"programmes, not tested interventions. A ratio below 1 may reflect a truly lower prevalence, testing or "
        f"recording, not only missed diabetes. Sources: India TB Report 2024; National Family Health Survey 2019–21 "
        f"State and Union Territory fact sheets.")]
    return Table("Table 1", "The tuberculosis–diabetes care cascade by State and Union Territory, 2023, and the step "
                 "to strengthen first",
                 ["State or Union Territory", "Screened, %", "Identification ratio (95% CI)", "Linked, %",
                  "Shortfall", "Largest gaps", "Rate", "First step"], rows, notes)


def build(root: Path = ROOT) -> list[Table]:
    return [table1(root)]


def render(root: Path = ROOT) -> str:
    return render_md(build(root)).replace(
        "# Tables (generated by exhibits/make_tables.py from outputs/; do not edit by hand)", HEADER, 1)


# --------------------------------------------------------------------------------------
# The supplement
# --------------------------------------------------------------------------------------
def supplement_tables(root: Path = ROOT) -> list[Table]:
    return make_online_material.tables(root, SUPPLEMENT_ORDER)


def notation_md() -> str:
    """The symbols of the supplementary tables (exhibits/make_online_material.NOTATION), in words."""
    items = "; ".join(f"{a}, {b}" for a, b in make_online_material.NOTATION)
    return ("## Notation\n\nThe manuscript describes these quantities in words; the supplementary tables use the "
            f"symbols: {items}. NFHS-5, National Family Health Survey 2019–21; NCD, non-communicable disease; TB, "
            "tuberculosis; UT, Union Territory.\n")


def supplement_md(root: Path = ROOT) -> str:
    md = render_md(supplement_tables(root)).replace(
        "# Tables (generated by exhibits/make_tables.py from outputs/; do not edit by hand)",
        SUPP_HEADER + "\n\n" + notation_md().rstrip("\n"), 1)
    return md + "\n## Figure S1\n\n" + FIGURE_S1_LEGEND + "\n"


def supplement_labels() -> tuple[list[str], list[str]]:
    """(the supplementary tables, the supplementary figures), as 'S1', 'S2', ..."""
    return [f"S{k}" for k in range(1, len(SUPPLEMENT_ORDER) + 1)], list(SUPPLEMENT_FIGURES)


# --------------------------------------------------------------------------------------
# Figures (colour, Okabe-Ito; words, not symbols)
# --------------------------------------------------------------------------------------
FIGURES = {1: fig1_data, 2: fig2_data, 3: fig3_data, "S1": fig4_data}


def setup():
    plt = make_figures.setup()
    plt.rcParams.update({"font.family": "DejaVu Sans", "hatch.linewidth": 0.6})
    return plt


def draw1(rows: list[dict], plt):
    fig, axes = plt.subplots(1, 3, figsize=(WIDTH, 2.7))
    years = [int(r["year"]) for r in rows]
    panels = [("A  Screened for diabetes\namong people notified with tuberculosis", "C1"),
              ("B  Diabetes identified\namong those screened (known or new)", "y"),
              ("C  Started diabetes treatment\namong those identified", "C3")]
    for ax, (title, key) in zip(axes, panels):
        for r, yr in zip(rows, years):
            v = 100 * float(r[key])
            other = key == "C3" and r["C3_definition"] != "initiated on treatment"
            ax.bar(yr, v, width=0.7, color="white" if other else BLUE, edgecolor=BLUE, lw=0.8,
                   hatch="////" if other else None)
            if key == "C1":
                ax.plot([yr, yr], [100 * float(r["C1_lo"]), 100 * float(r["C1_hi"])], color=BLACK, lw=0.8)
            ax.annotate(f"{num(v, 1)}%", (yr, v), xytext=(0, 2), textcoords="offset points", ha="center",
                        va="bottom", fontsize=6.3)
        ax.set_xticks(years)
        ax.set_xticklabels([str(y) for y in years])
        ax.set_title(title, loc="left", fontweight="bold", fontsize=6.8)
        top = 100 if key != "y" else 10
        ax.set_ylim(0, top * 1.1)
        ax.set_ylabel("Per cent")
        ax.set_xlabel("Data year")
    axes[2].annotate("2018: linked to\nan NCD clinic", (2018, 100 * float(rows[0]["C3"]) + 7), xytext=(2018, 88),
                     ha="center", va="bottom", fontsize=5.6, arrowprops=dict(arrowstyle="-", lw=0.5, color=BLACK))
    fig.subplots_adjust(left=0.065, right=0.99, top=0.84, bottom=0.15, wspace=0.32)
    return fig


def draw2(rows: list[dict], plt):
    fig, ax = plt.subplots(figsize=(WIDTH, 4.4), dpi=100)
    cb = 100 * float(rows[0]["c_b"])
    ax.axhline(1.0, color=BLACK, ls="--", lw=0.9, zorder=1)
    ax.axvline(cb, color=GREY, ls=":", lw=0.9, zorder=1)
    pts = []
    for r in rows:
        x = 100 * float(r["C1"])
        y, lo, hi = float(r["C2"]), float(r["C2_lo"]), float(r["C2_hi"])
        m, col, filled = CLASS_STYLE[r["class"]]
        ax.plot([x, x], [lo, hi], color=LIGHT, lw=0.8, zorder=2)
        ax.plot(x, y, marker=m, ms=4.8, mfc=col if filled else "white", mec=col, mew=1.0, ls="", zorder=3)
        pts.append((x, y, CODE[r["unit"]]))
    ax.set_yscale("log")
    ticks = [0.3, 0.5, 0.7, 1.0, 1.5, 2.0]
    ax.set_yticks(ticks)
    ax.set_yticklabels([num(t, 1) for t in ticks])
    ax.minorticks_off()
    xs = [100 * float(r["C1"]) for r in rows]
    ax.set_xlim(min(xs) - 3, 100.5)
    ax.set_ylim(0.22, 2.3)
    ax.set_xlabel("Screened for diabetes, % of people notified with tuberculosis (2023)")
    ax.set_ylabel("Identification relative to the benchmark (log scale)")
    ax.text(min(xs) - 2.6, 1.03, "identification at the benchmark", fontsize=6.2, va="bottom")
    ax.text(cb - 0.3, 0.23, f"benchmark coverage {num(cb, 1)}%", color=GREY, fontsize=6.2, ha="right", va="bottom")
    from matplotlib.lines import Line2D
    order = ("identification-led", "screening-led", "mixed")
    h = [Line2D([], [], marker=CLASS_STYLE[c][0], ls="", mfc=CLASS_STYLE[c][1] if CLASS_STYLE[c][2] else "white",
                mec=CLASS_STYLE[c][1], mew=1.0, ms=4.8) for c in order]
    n = {c: sum(r["class"] == c for r in rows) for c in order}
    ax.legend(h, [f"identification-led ({n['identification-led']})", f"screening-led ({n['screening-led']})",
                  f"mixed ({n['mixed']})"], loc="upper left", frameon=False, title="Where the shortfall lies, 2023",
              title_fontsize=6.5)
    fig.subplots_adjust(left=0.08, right=0.985, top=0.97, bottom=0.11)
    place_labels(ax, pts, fig)
    return fig


GAP_TITLE = {"E1": "A  Screening gap\nexpected among those not screened",
             "E2": "B  Identification gap\nexpected among those screened",
             "E3": "C  Linkage gap\nidentified, not started on treatment"}


def draw3(rows: list[dict], plt):
    units = sorted({r["unit"] for r in rows})
    fig, axes = plt.subplots(1, 3, figsize=(WIDTH, 6.4), sharey=True)
    for ax, g in zip(axes, ("E1", "E2", "E3")):
        cell = {r["unit"]: r for r in rows if r["gap"] == g}
        for i, u in enumerate(units):
            r = cell[u]
            act = r["tier"] == "act now"
            mean, lo, hi = float(r["mean"]), float(r["lo"]), float(r["hi"])
            ax.plot([lo, hi], [i, i], color=BLACK, lw=1.0, solid_capstyle="butt")
            ax.plot(mean, i, marker="D" if act else "o", ms=3.8 if act else 2.8, mfc=VERMILION if act else "white",
                    mec=VERMILION if act else GREY, mew=0.7, ls="")
            if act:
                ax.annotate("act now", (hi, i), xytext=(3, 0), textcoords="offset points", va="center", fontsize=5.6,
                            color=VERMILION)
        ax.set_ylim(len(units) - 0.4, -0.6)
        ax.set_yticks(range(len(units)))
        ax.set_yticklabels(units)
        xmax = max(float(r["hi"]) for r in cell.values())
        ax.set_xlim(0, xmax * 1.3)
        ax.xaxis.set_major_formatter(plt.FuncFormatter(lambda v, _: f"{v:,.0f}"))
        ax.set_title(GAP_TITLE[g], loc="left", fontweight="bold", fontsize=6.4)
        ax.grid(axis="y", color="#eeeeee", lw=0.5)
        ax.set_axisbelow(True)
    fig.supxlabel("People with tuberculosis and diabetes, 2023 (mean and 95% interval)", fontsize=7, x=0.59, y=0.012)
    fig.subplots_adjust(left=0.2, right=0.985, top=0.94, bottom=0.07, wspace=0.12)
    return fig


def drawS1(rows: list[dict], plt):
    fig = make_figures.draw4(rows, plt)
    make_online_material.relabel(fig)
    return fig


DRAW = {1: draw1, 2: draw2, 3: draw3, "S1": drawS1}


def write(ms_dir: Path, root: Path = ROOT, png: bool = True) -> list[str]:
    ex = ms_dir / "exhibits"
    ex.mkdir(parents=True, exist_ok=True)
    tables = build(root)
    (ex / "tables.md").write_text(render(root), encoding="utf-8", newline="\n")
    for t in tables:
        (ex / t.csv_name).write_bytes(csv_bytes(t))
    (ex / "supplement.md").write_text(supplement_md(root), encoding="utf-8", newline="\n")
    out = [f"{t.label}: {len(t.rows)} rows -> {t.csv_name}" for t in tables]
    out.append(f"supplement.md: {len(SUPPLEMENT_ORDER)} tables and {len(SUPPLEMENT_FIGURES)} figure legend(s)")
    plt = setup()
    for k, fn in FIGURES.items():
        rows = fn(root)
        (ex / f"figure{k}_data.csv").write_bytes(data_csv(rows))
        fig = DRAW[k](rows, plt)
        fig.savefig(ex / f"figure{k}.pdf", metadata={"CreationDate": None, "Creator": None, "Producer": None})
        if png:
            fig.savefig(ex / f"figure{k}.png", dpi=200)
        plt.close(fig)
        out.append(f"figure{k}.pdf: {len(rows)} data rows")
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0], allow_abbrev=False)
    ap.add_argument("--manuscript-dir", default=DEFAULT_MS_DIR)
    a = ap.parse_args(argv)
    d = Path(a.manuscript_dir)
    d = d if d.is_absolute() else ROOT / d
    for ln in write(d):
        print(ln)
    return 0


if __name__ == "__main__":
    sys.exit(main())
