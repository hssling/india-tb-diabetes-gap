def tables7(root: Path) -> Table:
    pr = {(r["unit"], r["gap"]): r for r in priority(root) if r["year"] == MAIN_YEAR and r["spec"] == "main"}
    rows = []
    for u in sorted({k[0] for k in pr}):
        cells = [u]
        for g in ("E1", "E2", "total"):
            r = pr[(u, g)]
            cells += [patients(r["mean"], r["lo"], r["hi"]), tier_cell(r["p_top5"], r["tier"])]
        cells.append(count(pr[(u, "total")]["per_100k_notified"]))
