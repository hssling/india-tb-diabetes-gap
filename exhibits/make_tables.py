class Table(NamedTuple):
    label: str            # "Table 1", "Table S3"
    title: str
    header: list[str]
    rows: list[list[str]]  # a spanning block label is ["**label**", "", ...]
    notes: list[str]

    @property
    def csv_name(self) -> str:
        """Table 1 -> table1.csv; Table S3 -> tables3.csv."""
        return "table" + self.label.split()[1].lower() + ".csv"


def block(label: str, ncol: int) -> list[str]:
    return [f"**{label}**"] + [""] * (ncol - 1)


def hs_rows(root: Path) -> list[dict]:
    return read_csv(root, "outputs/headline_sensitivity.csv")


def hs(root: Path, estimate: str, **kv) -> dict:
    return one(hs_rows(root), estimate, estimate=estimate, **kv)


def tier_cell(p: str, tier: str) -> str:
    return f"{prob(p)} ({tier})"


