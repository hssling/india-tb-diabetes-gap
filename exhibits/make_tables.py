def tables6(root: Path) -> Table:
    ca = [r for r in state_rows(read_csv(root, "outputs/cascade.csv")) if r["spec"] == "main"]
    by = {(r["unit"], r["year"]): r for r in ca}
    pr = {r["unit"]: r for r in priority(root) if r["year"] == MAIN_YEAR and r["gap"] == "E3" and r["spec"] == "main"}
    rows = []
    for u in sorted({r["unit"] for r in ca}):
        r18 = by[(u, "2018")]
        cells = [u, pct(r18["C3_linked_ncd_clinic_2018"])]
        for y in ("2019", "2021", "2022", "2023"):
            cells.append(pct(by[(u, y)]["C3"]))
        e = pr[u]
        cells += [patients(e["mean"], e["lo"], e["hi"]), tier_cell(e["p_top5"], e["tier"]),
                  "yes" if by[(u, MAIN_YEAR)]["linkage_below_benchmark"] == "True" else "no"]
        rows.append(cells)
    b = read_csv(root, "outputs/benchmark.csv")
    c3b = one(b, "c3_b 2023", kind="c3_b", year=MAIN_YEAR)
    notes = [f"C3: TB patients with diabetes initiated on anti-diabetic treatment among those identified (2018: linked to "
             f"an NCD clinic, a different definition). E3, the linkage gap = D − I (identified, not initiated), mean "
             f"and 95% interval of 10,000 Jeffreys draws of C3; P(top-5), the probability of being among the five units "
             f"with the largest E3, with its tier (act now at least 0.80). Linkage below the benchmark: P(C3 < c3_b) at "
             f"least 0.95, with c3_b = {pct(c3b['value'])} in 2023 (the 75th percentile of units). E3 is not added to the "
             f"screening and identification gaps."]
    return Table("Table S6", "Linkage to anti-diabetic treatment (C3) by year, and the linkage gap E3 in 2023",
                 ["Unit", "2018 (NCD clinic)", "2019", "2021", "2022", "2023", "E3, 2023 (95% interval)",
                  "P(top-5) (tier)", "Linkage below benchmark"], rows, notes)


