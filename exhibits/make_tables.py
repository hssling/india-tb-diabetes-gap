    tot = {g: sum(float(pr[(u, g)]["mean"]) for u in {k[0] for k in pr}) for g in ("E1", "E2", "total")}
    kb = main_kb(root)
    notes = [f"Main specification, 2023 (k_b = {ratio(kb, 3)}; 10,000 draws). E1 = N(1 − c)k_b p_u; E2 = K max(0, k_b p_u "
             f"− y); total = E1 + E2; mean and 95% interval. Tier from P(top-5): act now at least 0.80, lower priority "
             f"below 0.20. Sums of the means: E1 {count(tot['E1'])}; E2 {count(tot['E2'])}; total {count(tot['total'])}."]
    return Table("Table S7", "Screening gap (E1), identification gap (E2) and total shortfall, with tiers, 2023",
                 ["Unit", "E1 (95% interval)", "E1 P(top-5) (tier)", "E2 (95% interval)", "E2 P(top-5) (tier)",
                  "Total (95% interval)", "Total P(top-5) (tier)", "Total per 100,000 notified"], rows, notes)


