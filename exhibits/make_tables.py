def flags_cell(r: dict) -> str:
    out = []
    if r["below_benchmark"] == "True":
        out.append("B")
    if r["likely_under_detection"] == "True":
        out.append("U")
    if r.get("linkage_below_benchmark") == "True":
        out.append("L")
    return ", ".join(out) or DASH


def tables5(root: Path) -> Table:
    rows = []
    for r in cascade_main(root):
        rows.append([r["unit"], count(r["N"]), share_ci(r["C1"], r["C1_lo"], r["C1_hi"]),
                     share_ci(r["y"], r["y_lo"], r["y_hi"]), pct(r["p_u"]), ratio_ci(r["C2"], r["C2_lo"], r["C2_hi"]),
                     prob(r["P_R_kb_below_1"]), ratio_ci(r["R_k1"], r["R_k1_lo"], r["R_k1_hi"]),
                     share_ci(r["C3"], r["C3_lo"], r["C3_hi"]), flags_cell(r)])
    kb = main_kb(root)
    notes = [f"Data year 2023, main basis; Jeffreys intervals. C2 = y/(k_b p_u), k_b = {ratio(kb, 3)}; R at k = 1 = y/p_u. "
             f"Flags: B, below the benchmark (P(C2 < 1) at least 0.95); U, \"likely under-detection\" (97.5th percentile "
             f"of R at k = 1 below 1; may reflect the NFHS-5 threshold); L, linkage below the benchmark. A low C2 may "
             f"reflect a truly lower prevalence, the testing method or recording."]
    return Table("Table S5", "The State TB–diabetes cascade, data year 2023",
                 ["Unit", "Notified, N", "C1 screened", "y identified", "p_u", "C2 (95% interval)", "P(C2 < 1)",
                  "R at k = 1", "C3 initiated", "Flags"], rows, notes)


