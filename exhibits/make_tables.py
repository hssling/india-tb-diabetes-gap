# Table S3: benchmarks
# --------------------------------------------------------------------------------------
PERCENTILE = {"p75": "75th", "median": "50th (median)", "p90": "90th (best decile)"}
REFERENCE = {"sex_weighted": "sex-weighted", "simple": "simple"}
PRIOR = {"empirical_bayes": "empirical Bayes", "jeffreys": "Jeffreys (shrinkage off)"}
BASIS = {"main": "main basis", "denominator_a1_2_registered": "Annexure 1.2 (registered)",
         "denominator_2022_from_percent": "2022 from printed %"}


def tables3(root: Path) -> Table:
    b = read_csv(root, "outputs/benchmark.csv")
    rows = [block("Benchmark multiplier k_b (pooled identification relative to p_u)", 6)]
    for r in [x for x in b if x["kind"] == "k_b"]:
        rows.append([PERCENTILE[r["percentile"]], r["pool"].replace("+", " and "), REFERENCE[r["reference"]],
                     PRIOR[r["prior"]] + (" (main)" if r["is_main"] == "True" else ""), ratio(r["value"], 3), count(r["n_units"])])
    rows.append(block("Benchmark screening coverage c_b, 2023 (scenario)", 6))
    for r in [x for x in b if x["kind"] == "c_b"]:
        rows.append([PERCENTILE[r["percentile"]], DASH, DASH, f"{PRIOR[r['prior']]}; {BASIS[r['basis']]}",
                     pct(r["value"]), count(r["n_units"])])
    rows.append(block("Linkage benchmark c3_b (75th percentile of units' initiation share)", 6))
    for r in [x for x in b if x["kind"] == "c3_b"]:
        rows.append([PERCENTILE[r["percentile"]], r["year"], DASH, DASH, pct(r["value"]), count(r["n_units"])])
    notes = ["k_b is the stated percentile across units of the posterior-mean yield (empirical-Bayes beta-binomial, or "
             "the Jeffreys prior with shrinkage off) divided by p_u; the expected yield is k_b p_u. Because k_b is a "
             "percentile, about a quarter of units lie above the 75th-percentile benchmark by construction. A common "
             "scaling of p_u cancels under k_b. c_b is the 75th percentile of units' posterior-mean screening coverage "
             "in 2023; c3_b is the 75th percentile of the Jeffreys posterior means of C3. Pool, data years; the 2019 "
             "and 2021 pool is a sensitivity."]
    return Table("Table S3", "Benchmarks: the multiplier k_b, the benchmark coverage and the linkage benchmark",
                 ["Percentile", "Pool or year", "Reference", "Prior and basis", "Value", "Units"], rows, notes)


