def tables1(root: Path) -> Table:
    panel = read_csv(root, "data/extracted/dm_panel.csv")
    groups: dict[tuple[str, str], list[dict]] = defaultdict(list)
    for r in panel:
        groups[(r["year"], r["measure"])].append(r)
    rows = []
    for year in sorted({k[0] for k in groups}):
        for ms in (("notified",), ("known_status", "diabetic", "initiated")):
            rs = [r for m in ms for r in groups[(year, m)]]
            tables = sorted({r["table_id"] for r in rs})
            pages = sorted({int(x) for r in rs for x in r["pdf_page"].split(";")})
            files = {r["source_file"].split("/")[-1] for r in rs}
            if len(tables) != 1 or len(files) != 1:
                raise ValueError(f"S1 {year} {ms}: {tables} {files}")
            flags = []
            for r in rs:
                for f in r["flag"].split(";"):
                    if f and not f.startswith("merged:") and f not in flags:
                        flags.append(f)
            words = "; ".join(FLAG_WORDS[f] for f in flags) or DASH
            pg = f"p. {pages[0]}" if len(pages) == 1 else f"pp. {pages[0]}–{pages[-1]}"
            units = {count(len(groups[(year, m)])) for m in ms}
            (n_units,) = units
            rows.append([year, REPORT[files.pop()], ", ".join(MEASURE[m] for m in ms), f"{tables[0]} (PDF {pg})",
                         n_units, words])
    na = read_csv(root, "outputs/na_cells.csv")
    n_na = {s: sum(1 for r in na if r["spec"] == s and r["kind"] == "NA") for s in ("main", "denominator_a1_2_registered")}
    na_units = sorted({r["unit"] for r in na if r["kind"] == "NA"})
    notes = [
        "Units: 33 after coarsening (Dadra and Nagar Haveli and Daman and Diu with Gujarat, Lakshadweep with Kerala, "
        "Ladakh with Jammu and Kashmir). The Total column (public and private) is used in every year. C2's "
        "denominator is K and C3's is D, from the same diabetes table. Main N for 2021 to 2023 follows plan section "
        "12.1 (the basis of the printed known-status percentages); the registered Annexure 1.2 notified count "
        "(diagnosing facility) is a sensitivity, and for 2022 a second sensitivity back-calculates N from the printed "
        f"percentage. NA cells: {count(n_na['main'])} on the main basis; {count(n_na['denominator_a1_2_registered'])} on "
        f"the Annexure 1.2 basis ({and_list(na_units)}, 2021 to 2023: known status above notified). The 2018 C3 "
        "(linked to an NCD clinic) is not compared with later years."]
    return Table("Table S1", "Sources, tables and definitions by data year",
                 ["Data year", "Report", "Measure", "Table", "Units", "Basis and notes"], rows, notes)


