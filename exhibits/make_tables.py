    wald = hs(root, "H1_wald_interval", spec="main")
    nobs = hs(root, "H1_n_obs", spec="main")
    sp = hs(root, "H1_spearman_fieller", spec="sex_weighted 2019+2021")
    loo = read_csv(root, "outputs/leave_one_out.csv")
